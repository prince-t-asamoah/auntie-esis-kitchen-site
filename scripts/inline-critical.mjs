// Dev-only: copy the above-the-fold sections of css/styles.css into each page's <head>.
// Run after editing css/styles.css: npm run inline-css
//
// css/styles.css stays the single source of truth. Its sections start with a comment at the
// start of a line ("/* Hero */"); each page lists the section names it needs before first
// paint. The output goes between the critical-css markers in the HTML; don't edit it by hand.
import { readFile, writeFile } from "node:fs/promises";

const BASE = ["Auntie Esi's Kitchen", "Reset + base", "Buttons", "Header", "Floating WhatsApp button"];
const PAGES = {
  "index.html": [...BASE, "Hero"],
  "contact/index.html": [...BASE, "Find us + info cards", "Contact page"],
};

const css = await readFile("css/styles.css", "utf8");

// Split into sections at top-level comments; key each by its comment's first line.
const sections = new Map();
for (const chunk of css.split(/^(?=\/\* )/m)) sections.set(chunk.slice(3, chunk.indexOf("\n")), chunk);

const minify = (s) =>
  s
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{}:;,>])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();

const START = "<!-- critical-css:start (generated by npm run inline-css; edit css/styles.css instead) -->";
const END = "<!-- critical-css:end -->";

for (const [file, names] of Object.entries(PAGES)) {
  const picked = names.map((n) => {
    const hit = [...sections.keys()].find((k) => k.startsWith(n));
    if (!hit) throw new Error(`${file}: no CSS section starting "${n}"`);
    return sections.get(hit);
  });
  const style = `${START}\n<style>${minify(picked.join("\n"))}</style>\n${END}`;
  const html = await readFile(file, "utf8");
  const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
  if (!re.test(html)) throw new Error(`${file}: critical-css markers not found`);
  await writeFile(file, html.replace(re, () => style));
  console.log(`${file}: ${(style.length / 1024).toFixed(1)} KB inlined from ${names.length} sections`);
}
